"""Read the job-match Turtle schema as Python/Pydantic instance models.

This handles the schema's explicitly declared classes and single domain/range
properties, not general OWL reasoning. Loading does not populate a graph or call
an LLM. Object properties hold node IRIs; validate_instances checks their targets.
"""

import re
from pathlib import Path
from typing import ClassVar, Literal

from pydantic import BaseModel, ConfigDict, Field, PrivateAttr, SerializeAsAny, create_model, field_serializer
from rdflib import Graph, RDF, RDFS, OWL, XSD, URIRef
from rdflib.namespace import split_uri


SCHEMA_PATH = Path(__file__).resolve().parents[2] / "data/ontologies/resume-job.ttl"
IRI_PATTERN = r'^[A-Za-z][A-Za-z0-9+.-]*:[^\s<>"{}|\\^`]+$'
DATATYPES = {XSD.integer: int, XSD.float: float, XSD.string: str, XSD.boolean: bool}


class TaxonomyReference(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    id: str
    namespace: str
    label: str
    source_version: str


class SourceEvidence(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    entity_id: str
    source_document: str
    source_field: str
    start: int = Field(ge=0)
    end: int = Field(gt=0)
    text: str
    label: str
    extraction_sources: list[str] = Field(default_factory=list)
    classification_conflicts: list[str] = Field(default_factory=list)


class EmploymentDuration(BaseModel):
    """Month-precision derivation using only one employment header's source text."""

    model_config = ConfigDict(extra="forbid", strict=True)
    start_month: str = Field(pattern=r"^\d{4}-(?:0[1-9]|1[0-2])$")
    end_month: str = Field(pattern=r"^\d{4}-(?:0[1-9]|1[0-2])$")
    as_of_month: str = Field(pattern=r"^\d{4}-(?:0[1-9]|1[0-2])$")
    months: int = Field(ge=0)
    ongoing: bool
    method: Literal["calendar_month_difference"] = "calendar_month_difference"
    source_field: Literal["section_texts.experience"] = "section_texts.experience"
    start: int = Field(ge=0)
    end: int = Field(gt=0)
    text: str


class NodeMetadata(BaseModel):
    """JSON transport metadata, separate from properties declared in the TTL."""

    model_config = ConfigDict(extra="forbid", strict=True)
    label: str | None = None
    taxonomy: TaxonomyReference | None = None
    original_title: str | None = None
    resolution_status: Literal["resolved", "unresolved"] | None = None
    resolution_reason: str | None = None
    duration: EmploymentDuration | None = None
    evidence: list[SourceEvidence] = Field(default_factory=list)


class OntologyNode(BaseModel):
    """Base for generated classes; id identifies an individual, not an OWL class."""

    model_config = ConfigDict(extra="forbid", strict=True, populate_by_name=True,
                              allow_inf_nan=False)
    rdf_type: ClassVar[str]
    id: str = Field(pattern=IRI_PATTERN)
    metadata: NodeMetadata = Field(default_factory=NodeMetadata)


class OntologyProperty(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    iri: str
    field_name: str
    kind: str
    domain: str
    range: str


class OntologyDocument(BaseModel):
    """Final populated resume, preserving generated node fields and RDF types."""

    model_config = ConfigDict(extra="forbid")
    cv_id: str
    nodes: list[SerializeAsAny[OntologyNode]]

    @field_serializer("nodes")
    def serialize_nodes(self, nodes):
        return [{"type": node.rdf_type, **node.model_dump(mode="json", by_alias=True, exclude_none=True)}
                for node in nodes]


class OntologyOutput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    resumes: list[OntologyDocument]


class OntologySchema(BaseModel):
    """Schema metadata and generated models, keyed by the TTL class local names."""

    model_config = ConfigDict(extra="forbid")
    source: Path
    classes: dict[str, str]
    properties: dict[str, OntologyProperty]
    _models: dict[str, type[OntologyNode]] = PrivateAttr(default_factory=dict)

    @property
    def models(self) -> dict[str, type[OntologyNode]]:
        return dict(self._models)

    def validate_instances(self, nodes: list[OntologyNode]) -> None:
        """Validate a complete instance set, including object-reference types.

        References must be present in this set, including shared taxonomy nodes.
        This does not establish that a relationship is supported by resume text.
        """
        by_id = {}
        for node in nodes:
            if type(node) not in self._models.values():
                raise ValueError("Node must use a model generated by this schema")
            # Revalidate in case a caller mutated a field after construction.
            type(node).model_validate(node.model_dump(), strict=True)
            if node.id in by_id:
                raise ValueError(f"Duplicate node ID: {node.id}")
            by_id[node.id] = node
        for node in nodes:
            for prop in self.properties.values():
                if prop.kind != "object" or prop.domain != node.rdf_type:
                    continue
                for target_id in getattr(node, prop.field_name):
                    target = by_id.get(target_id)
                    if target is None:
                        raise ValueError(f"Missing target for {prop.iri}: {target_id}")
                    if target.rdf_type != prop.range:
                        raise ValueError(f"Wrong target type for {prop.iri}: expected {prop.range}")


def _local_name(iri: URIRef) -> str:
    return split_uri(iri)[1]


def _one_iri(graph: Graph, subject: URIRef, predicate: URIRef) -> URIRef:
    values = list(graph.objects(subject, predicate))
    if len(values) != 1 or not isinstance(values[0], URIRef):
        raise ValueError(f"Expected one named {predicate} for {subject}")
    return values[0]


def load_ontology(path: str | Path = SCHEMA_PATH) -> OntologySchema:
    """Generate strict models from named classes and explicit domain/range pairs.

    Properties are lists because the current TTL declares no cardinality limits.
    Empty lists mean no assertion, not that an applicant has no skills/experience.
    Python uses snake_case fields; model_dump(by_alias=True) uses TTL local names.
    Unsupported datatypes and domain/range expressions raise instead of guessing.
    """
    path = Path(path).resolve()
    graph = Graph().parse(path, format="turtle")
    class_iris = sorted(graph.subjects(RDF.type, OWL.Class), key=str)
    if not class_iris or any(not isinstance(iri, URIRef) for iri in class_iris):
        raise ValueError("Schema must declare named OWL classes")
    classes = {_local_name(iri): str(iri) for iri in class_iris}
    if len(classes) != len(class_iris):
        raise ValueError("Class local names must be unique")
    fields = {str(iri): {} for iri in class_iris}
    properties = {}
    for rdf_kind, kind in ((OWL.ObjectProperty, "object"), (OWL.DatatypeProperty, "datatype")):
        for iri in sorted(graph.subjects(RDF.type, rdf_kind), key=str):
            if not isinstance(iri, URIRef) or str(iri) in properties:
                raise ValueError("Properties must be named and have one property kind")
            domain = _one_iri(graph, iri, RDFS.domain)
            range_iri = _one_iri(graph, iri, RDFS.range)
            if str(domain) not in fields:
                raise ValueError(f"Undeclared property domain: {domain}")
            if kind == "object":
                if str(range_iri) not in fields:
                    raise ValueError(f"Undeclared object range: {range_iri}")
                value_type = str
            else:
                if range_iri not in DATATYPES:
                    raise ValueError(f"Unsupported datatype: {range_iri}")
                value_type = DATATYPES[range_iri]
            alias = _local_name(iri)
            name = re.sub(r"(?<!^)(?=[A-Z])", "_", alias).lower()
            if (not name.isidentifier() or name.startswith("_") or name.startswith("model_")
                    or hasattr(OntologyNode, name) or name in OntologyNode.model_fields or name in fields[str(domain)]):
                raise ValueError(f"Unsupported or colliding field name: {alias}")
            properties[str(iri)] = OntologyProperty(
                iri=str(iri), field_name=name, kind=kind, domain=str(domain), range=str(range_iri))
            fields[str(domain)][name] = (
                list[value_type], Field(default_factory=list, alias=alias,
                                        json_schema_extra={"rdf_property": str(iri), "rdf_range": str(range_iri)}))
    schema = OntologySchema(source=path, classes=classes, properties=properties)
    for name, iri in classes.items():
        model = create_model(name, __base__=OntologyNode, __module__=__name__, **fields[iri])
        model.rdf_type = iri
        schema._models[name] = model
    return schema
